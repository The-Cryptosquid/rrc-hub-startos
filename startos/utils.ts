// "10.0.3.1:4242" -> { host, port }
export const splitAddress = (address: string) => {
  const at = address.lastIndexOf(':')
  return { host: address.slice(0, at), port: Number(address.slice(at + 1)) }
}

// The hub's Reticulum config, rendered whole from the package's settings on
// every start. Transport is off: the hub serves its own channels and does not
// route traffic for others.
export const renderRnsConfig = (connections: Connection[]) => {
  const outbound = connections
    .map(
      (c, ii) => `
  [[${(c.name || `Server ${ii + 1}`).replace(/[\[\]\n]/g, '')}]]
    type = TCPClientInterface
    enabled = yes
    target_host = ${c.host}
    target_port = ${c.port}
`,
    )
    .join('')
  return `# Generated by the RRC Hub StartOS package on every start. Do not edit:
# change network connections with the "Network Connections" action.

[reticulum]
  enable_transport = No
  share_instance = No
  panic_on_interface_error = No

[logging]
  loglevel = 3

[interfaces]

  # Phones and computers connect here directly with a TCP Client Interface.
  [[StartOS TCP Server]]
    type = TCPServerInterface
    enabled = yes
    listen_ip = ::
    listen_port = ${rnsPort}
${outbound}`
}

export type SeenUser = { nick?: string; last_seen: number }

// The identities an operator might act on: everyone who has connected, plus
// anyone already named in a permission list (who may not have connected since
// it was set). Most recently seen first; the never-seen ones last.
export const knownUsers = (
  seen: Record<string, SeenUser>,
  named: string[],
  limit = 50,
) => {
  const recent = Object.entries(seen)
    .map(([hash, u]) => ({ hash: normalizeHash(hash), ...u }))
    .sort((a, b) => b.last_seen - a.last_seen)
  const namedSet = new Set(named.map(normalizeHash))
  const shown = recent.filter((u, ii) => ii < limit || namedSet.has(u.hash))
  const seenSet = new Set(recent.map((u) => u.hash))
  const unseen = [...namedSet]
    .filter((h) => !seenSet.has(h))
    .map((hash) => ({ hash, nick: undefined, last_seen: 0 }))
  return [...shown, ...unseen]
}

export const formatTime = (unixSeconds: number) =>
  unixSeconds > 0
    ? new Date(unixSeconds * 1000).toISOString().slice(0, 16).replace('T', ' ')
    : null

// rrcd reads its files only at startup, so a change made by an action takes
// effect when the hub restarts. Clients drop and rejoin within seconds.
export const restartHub = (effects: Parameters<typeof sdk.restart>[0]) =>
  sdk.restart(effects)
