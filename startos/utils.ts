// A Reticulum identity hash: 16 bytes as 32 hex characters.
export const identityHashRegex = '^[0-9a-fA-F]{32}$'

export const normalizeHash = (hash: string) =>
  hash.trim().toLowerCase().replace(/^0x/, '')

// rrcd lowercases and trims room names, and refuses names over 64 UTF-8 bytes.
export const maxRoomNameBytes = 64
export const normalizeRoom = (room: string) => room.trim().toLowerCase()
export const roomNameBytes = (room: string) =>
  new TextEncoder().encode(room).length

export const shortHash = (hash: string) => `${hash.slice(0, 12)}…`

// How often the hub re-announces itself so clients can discover it.
export const announceIntervals = {
  '900': '15 min',
  '1800': '30 min',
  '3600': '1 h',
  '21600': '6 h',
  '43200': '12 h',
  '86400': '24 h',
} as const
export type AnnounceInterval = keyof typeof announceIntervals
export const defaultAnnounceInterval: AnnounceInterval = '1800'
const isAnnounceInterval = (key: string): key is AnnounceInterval =>
  key in announceIntervals
export const toAnnounceInterval = (seconds: number): AnnounceInterval => {
  const key = String(Math.round(seconds))
  return isAnnounceInterval(key) ? key : defaultAnnounceInterval
}

